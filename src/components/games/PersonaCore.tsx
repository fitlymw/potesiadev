/** Stability is shown instead of Neuroticism: flip score, z and level. */
function displayTrait(profile: BfiProfile, trait: Trait) {
  const s = profile[trait];
  const refPomp = ((REFERENCE_NORMS[trait].mean - 1) / 4) * 100;
  if (trait !== 'N') return { value: s.pomp, level: s.level, refPomp };
  const flipped: TraitLevel = s.level === 'high' ? 'low' : s.level === 'low' ? 'high' : 'moderate';
  return { value: 100 - s.pomp, level: flipped, refPomp: 100 - refPomp };
}

