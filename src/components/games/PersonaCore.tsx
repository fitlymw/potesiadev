// ==================== RADAR CHART ====================
function RadarChart({ values }: { values: Record<Trait, number> }) {
  const labels = ['E', 'A', 'C', 'ES', 'O'];
  const data = [values.E, values.A, values.C, values.N, values.O];
  const center = 70, radius = 60;

  const getPoint = (index: number, value: number) => {
    const angle = (index * 72 - 90) * (Math.PI / 180);
    const r = (value / 100) * radius;
    return { x: center + r * Math.cos(angle), y: center + r * Math.sin(angle) };
  };

  const points = data.map((v, i) => getPoint(i, v));
  const pathData = points.map((p, i) => `${i === 0 ? 'M' : 'L'} ${p.x} ${p.y}`).join(' ') + ' Z';

  return (
    <svg viewBox="-12 -12 164 164" className="w-full h-full max-h-72">
      {[20, 40, 60, 80, 100].map(r => <circle key={r} cx={center} cy={center} r={(r/100)*radius} fill="none" stroke="rgba(6,182,212,0.2)" strokeWidth="0.5" />)}
      {labels.map((_, i) => { const p = getPoint(i, 100); return <line key={i} x1={center} y1={center} x2={p.x} y2={p.y} stroke="rgba(6,182,212,0.3)" strokeWidth="0.5" />; })}
      {labels.map((label, i) => { const p = getPoint(i, 115); return <text key={label} x={p.x} y={p.y} fill="#06b6d4" fontSize="8" textAnchor="middle" dominantBaseline="middle" fontFamily="monospace">{label}</text>; })}
      <motion.path d={pathData} fill="rgba(6,182,212,0.3)" stroke="#06b6d4" strokeWidth="2" initial={{ opacity: 0 }} animate={{ opacity: 1 }} transition={{ duration: 1, delay: 0.5 }} />
      {points.map((p, i) => <motion.circle key={i} cx={p.x} cy={p.y} r="3" fill="#06b6d4" initial={{ opacity: 0, scale: 0 }} animate={{ opacity: 1, scale: 1 }} transition={{ duration: 0.3, delay: 0.8 + i * 0.1 }} />)}
    </svg>
  );
}

// ==================== CAREER (n8n) ====================
function CareerSection({ lang, result }: { lang: Lang; result: PersonaResult }) {
  const t = UI[lang];
  const [degree, setDegree] = useState('');
  const [records, setRecords] = useState<AcademicRecord[]>([
    { subject: '', score: '' },
    { subject: '', score: '' },
    { subject: '', score: '' },
  ]);
  const [career, setCareer] = useState<CareerState>({ status: 'idle' });

  const updateRecord = (idx: number, field: keyof AcademicRecord, value: string) =>
    setRecords((prev) => prev.map((r, i) => (i === idx ? { ...r, [field]: value } : r)));

  const filled = records.filter((r) => r.subject.trim() && r.score !== '');
  const scoresValid = filled.every((r) => Number(r.score) >= 0 && Number(r.score) <= 100);
  const canSubmit = degree.trim() !== '' && filled.length > 0 && scoresValid && career.status !== 'loading';

  const submit = async () => {
    if (!N8N_WEBHOOK_URL) return;
    setCareer({ status: 'loading' });
    const { profile, matches } = result;
    const payload = {
      user_profile: {
        degree: degree.trim(),
        academic_records: filled.map((r) => ({ subject: r.subject.trim(), score: Number(r.score) })),
        bfi_scores: { E: profile.E.pomp, A: profile.A.pomp, C: profile.C.pomp, N: profile.N.pomp, O: profile.O.pomp },
        bfi_levels: { E: profile.E.level, A: profile.A.level, C: profile.C.level, N: profile.N.level, O: profile.O.level },
        archetype: matches[0].archetype.name.en,
        language: lang,
      },
    };
    try {
      const response = await fetch(N8N_WEBHOOK_URL, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload),
      });
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      const data = await response.json();
      if (!Array.isArray(data?.top_jobs)) throw new Error('Unexpected response format');
      setCareer({ status: 'done', jobs: data.top_jobs });
    } catch (error) {
      console.error('Career analysis failed:', error);
      setCareer({ status: 'error', message: error instanceof Error ? error.message : String(error) });
    }
  };

  return (
    <motion.div initial={{ opacity: 0, y: 20 }} animate={{ opacity: 1, y: 0 }} transition={{ delay: 0.6 }} className="border border-cyan-500/30 bg-cyan-950/10 p-6 space-y-4">
      <div className="flex items-center gap-2 text-cyan-400 text-xs uppercase tracking-wider"><Terminal className="w-4 h-4" /><span>{t.career}</span></div>

      {career.status !== 'done' && (
        <div className="space-y-4">
          <div>
            <label className="block text-cyan-500/70 text-xs mb-2 font-mono">{t.degree}</label>
            <input type="text" value={degree} onChange={(e) => setDegree(e.target.value)} placeholder="e.g. Information Systems" className="w-full bg-black/50 border border-cyan-500/30 p-3 text-cyan-400 font-mono outline-none focus:border-cyan-400" />
          </div>
          <div>
            <label className="block text-cyan-500/70 text-xs mb-2 font-mono">{t.subjects}</label>
            {records.map((record, idx) => (
              <div key={idx} className="flex gap-2 mb-2">
                <input type="text" placeholder={t.subject} value={record.subject} onChange={(e) => updateRecord(idx, 'subject', e.target.value)} className="flex-1 min-w-0 bg-black/50 border border-cyan-500/30 p-2 text-cyan-400 font-mono text-sm outline-none focus:border-cyan-400" />
                <input type="number" min={0} max={100} placeholder={t.score} value={record.score} onChange={(e) => updateRecord(idx, 'score', e.target.value)} className="w-24 bg-black/50 border border-cyan-500/30 p-2 text-cyan-400 font-mono text-sm outline-none focus:border-cyan-400" />
              </div>
            ))}
          </div>
          <button disabled={!canSubmit} onClick={submit} className="w-full py-3 bg-cyan-950 border border-cyan-500 text-cyan-400 font-mono hover:bg-cyan-900 transition-colors disabled:opacity-50 flex items-center justify-center gap-2">
            {career.status === 'loading' ? <><Loader2 className="w-4 h-4 animate-spin" />{t.analyzing}</> : career.status === 'error' ? t.retry : `${t.analyze} >>`}
          </button>
          {career.status === 'error' && <p className="text-red-400/80 text-xs font-mono">! {career.message}</p>}
        </div>
      )}

      {career.status === 'done' && (
        <div className="space-y-3">
          <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
            {career.jobs.map((job, idx) => (
              <div key={idx} className="p-5 border border-cyan-500/30 bg-cyan-950/20 relative">
                <div className="absolute top-0 right-0 px-2 py-1 bg-cyan-900/50 text-cyan-200 font-mono text-xs border-l border-b border-cyan-500/30">{job.probability}%</div>
                <h3 className="text-lg text-cyan-100 font-bold mb-3 pr-12 flex items-center gap-2"><Briefcase className="w-4 h-4 shrink-0" />{job.title}</h3>
                <p className="text-cyan-400/80 text-sm font-mono leading-relaxed">{job.explanation}</p>
              </div>
            ))}
          </div>
          <p className="text-cyan-500/50 text-xs font-mono">{t.aiNote}</p>
        </div>
      )}
    </motion.div>
  );
}

/** Level word for an archetype target, phrased the way the UI shows the trait (N as stability). */
function targetLevel(trait: Trait, target: -1 | 0 | 1): TraitLevel {
  const level: TraitLevel = target > 0 ? 'high' : target < 0 ? 'low' : 'moderate';
  if (trait !== 'N' || level === 'moderate') return level;
  return level === 'high' ? 'low' : 'high';
}

// ==================== POSITIVE & NEGATIVE TRAITS ====================
function InsightsSection({ lang, insights, profile, answers }: { lang: Lang; insights: Insight[]; profile: BfiProfile; answers: number[] }) {
  const t = UI[lang];
  const describeBasis = (basis: InsightBasis) => {
    if (basis.kind === 'trait') {
      const shown = displayTrait(profile, basis.trait);
      return `${t.traitNames[basis.trait]} ${Math.round(shown.value)} (${t.levels[shown.level]})`;
    }
    const index = BFI_ITEMS.findIndex((item) => item.id === basis.itemId);
    return `"${BFI_ITEMS[index].text[lang]}" → ${t.yourAnswer}: ${LIKERT_LABELS[lang][answers[index] - 1]}`;
  };

  return (
    <motion.div initial={{ opacity: 0, y: 20 }} animate={{ opacity: 1, y: 0 }} transition={{ delay: 0.25 }} className="border border-cyan-500/30 bg-cyan-950/10 p-6">
      <div className="flex items-center gap-2 text-cyan-400 text-xs mb-1 uppercase tracking-wider"><Scale className="w-4 h-4" /><span>{t.insights}</span></div>
      <p className="text-cyan-300/50 text-xs mb-4">{t.insightsSub}</p>
      <div className="space-y-3">
        {insights.map((insight) => (
          <div key={insight.tag} className="border border-cyan-500/20 bg-black/30 p-4">
            <div className="grid grid-cols-1 md:grid-cols-2 gap-3">
              <div className="flex items-start gap-2">
                <ThumbsUp className="w-4 h-4 text-emerald-400 shrink-0 mt-0.5" />
                <div>
                  <p className="text-emerald-400/80 text-[11px] uppercase tracking-wider">{t.positive}</p>
                  <p className="text-cyan-50/90 text-sm leading-relaxed">{insight.positive[lang]}</p>
                </div>
              </div>
              <div className="flex items-start gap-2">
                <AlertTriangle className="w-4 h-4 text-amber-400 shrink-0 mt-0.5" />
                <div>
                  <p className="text-amber-400/80 text-[11px] uppercase tracking-wider">{t.negative}</p>
                  <p className="text-cyan-50/90 text-sm leading-relaxed">{insight.negative[lang]}</p>
                </div>
              </div>
            </div>
            <p className="text-cyan-400/40 text-[11px] mt-3 font-mono">{t.basis}: {insight.basis.map(describeBasis).join(' · ')}</p>
          </div>
        ))}
      </div>
    </motion.div>
  );
}

